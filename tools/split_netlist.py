#!/usr/bin/env python3
"""Split the reference full-chain netlist into per-stage netlists for the plugin.

Usage: split_netlist.py <reference.cir> <output dir>

Each stage keeps the original node names; nodes shared between stages become one-way links made
in code (see Source/Chain). Behavioural (B) elements and the test bench are dropped, the
sub-circuit bodies are not copied (the loader knows OPAMP / TRIODE / MPSA29 / TIP112).
"""
import re, sys, os

SECTIONS = [  # (marker found in the section comment, block)
    ("Phantom", "mic"), ("Coupling, clamps", "mic"), ("Mic pre:", "mic"),
    ("J1 normal", "inst"), ("Tube stage V1", "tube"), ("PREAMP OUTPUT", "preout"),
    ("Compressor audio path", "comp"), ("EQ insert", "eq1"), ("EQ: A10B", "eq1"),
    ("LOW / HIGH Baxandall", "eq2"), ("Hi-MID", "eq3"), ("Lo-MID", "eq4"),
    ("EQ bypass", "out"), ("MASTER and output", "out"),
]

def main():
    src, outdir = sys.argv[1], sys.argv[2]
    text = open(src).read().splitlines()
    header, models, params = [], [], []
    blocks = {b: [] for _, b in SECTIONS}
    in_sub = in_unit = after = False
    cur = None
    for line in text:
        low = line.strip().lower()
        if low.startswith(".subckt"):
            in_sub, in_unit = True, "proch2" in low
            continue
        if low.startswith(".ends"):
            if in_unit: after = True
            in_sub = in_unit = False
            continue
        if after:
            continue
        if low.startswith(".param") and not in_sub:
            params.append(line); continue
        if low.startswith(".model") and not in_sub:
            models.append(line); continue
        if in_sub and not in_unit:
            continue
        if in_unit:
            if line.startswith("*---"):
                cur = None
                for key, b in SECTIONS:
                    if key in line:
                        cur = b
                continue
            if not line.strip() or line.startswith("*") or cur is None:
                continue
            if line[0] in "Bb":                      # behavioural sources are modelled in code
                continue
            blocks[cur].append(line)
    os.makedirs(outdir, exist_ok=True)
    for name, lines in blocks.items():
        if not lines:
            continue
        with open(os.path.join(outdir, name + ".net"), "w") as f:
            f.write("* Tube Channel stage netlist: %s (generated by tools/split_netlist.py)\n" % name)
            f.write("\n".join(params) + "\n\n" + "\n".join(models) + "\n\n")
            f.write("\n".join(lines) + "\n")
        print(name, len(lines), "elements")

main()
